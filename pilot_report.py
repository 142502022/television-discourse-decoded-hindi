"""Assemble the pilot-episode markdown report from the analysis artifacts (Phase 6).

The report is generated, never hand-written: it reads each versioned JSON
artifact, summarises what it contains, marks any that are missing or stale, and
prints the exact commands that reproduce every artifact. Run ``make report``
after the analysis phases to refresh it.
"""
from __future__ import annotations

import argparse
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Optional

VERSION = "0.1.0"


@dataclass(frozen=True)
class ReportPaths:
    audit: Path = Path("pilot_episode_audit.json")
    host: Path = Path("data/v2/analysis/host_identification.json")
    topic_modeling: Path = Path("data/v2/topic_analysis/topic_modeling.json")
    topic_review: Path = Path("data/v2/topic_analysis/topic_modeling_review.json")
    topic_windows: Path = Path("data/v2/topic_analysis/topic_windows.json")
    topic_segmentation: Path = Path("data/v2/topic_analysis/topic_analysis_sample.json")
    drift: Path = Path("data/v2/topic_analysis/interruption_topic_drift.json")
    discourse: Path = Path("data/v2/analysis/discourse_summary.json")
    discourse_review: Path = Path("data/v2/analysis/discourse_summary_review.json")
    output: Path = Path("PILOT_EPISODE_REPORT.md")


SOURCE_LABELS = {
    "audit": "Pilot episode audit (Phase 1)",
    "host": "Host identification (Phase 2)",
    "topic_modeling": "Topic modeling timeline (Phase 3)",
    "topic_review": "Topic modeling review (Phase 3)",
    "topic_windows": "Topic windows table (Phase 3)",
    "topic_segmentation": "Topic boundary segmentation sample",
    "drift": "Interruption -> topic drift (Phase 5)",
    "discourse": "Discourse metric summary (Phase 4)",
    "discourse_review": "Discourse summary validation (Phase 4)",
}


def g(node: Any, *path: str, default: Any = None) -> Any:
    for key in path:
        if isinstance(node, dict) and key in node:
            node = node[key]
        else:
            return default
    return node


def fmt(value: Any) -> str:
    if value is None:
        return "n/a"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, float):
        return f"{value:g}"
    return str(value)


def load(path: Path) -> Optional[dict[str, Any]]:
    if not path.is_file():
        return None
    try:
        with path.open(encoding="utf-8") as handle:
            data = json.load(handle)
    except (OSError, json.JSONDecodeError):
        return None
    return data if isinstance(data, dict) else None


def load_sources(paths: ReportPaths) -> dict[str, Optional[dict[str, Any]]]:
    return {key: load(getattr(paths, key)) for key in SOURCE_LABELS}


def header(sources: dict[str, Optional[dict[str, Any]]], paths: ReportPaths) -> str:
    topic_modeling = sources.get("topic_modeling") or {}
    episode = g(topic_modeling, "episodes", default=[])
    metadata = episode[0]["metadata"] if episode and isinstance(episode[0], dict) else {}
    discourse = sources.get("discourse") or {}
    discourse_metadata = g(discourse, "episodes", default=[{}])
    discourse_metadata = discourse_metadata[0].get("metadata", {}) if discourse_metadata else {}
    video_id = fmt(g(metadata, "video_id", default=g(discourse_metadata, "video_id", default="unknown")))
    title = fmt(g(metadata, "title", default=g(discourse_metadata, "title")))
    duration = fmt(g(metadata, "duration_s", default=g(discourse_metadata, "duration_s")))

    lines = [f"# Pilot Episode Report: {video_id}", "",
             "Generated by `pilot_report.py` from the versioned JSON artifacts below. "
             "Topic labels, detected changes, and interruption associations are candidate outputs and require human review.", "",
             "| field | value |", "| --- | --- |",
             f"| title | {title} |", f"| duration | {duration} s |",
             f"| generated by | pilot_report.py v{VERSION} |", "",
             "## Artifact inventory", "", "| artifact | path | status | schema |", "| --- | --- | --- | --- |"]
    for key, label in SOURCE_LABELS.items():
        document = sources.get(key)
        status = "present" if document is not None else "MISSING"
        schema = fmt(g(document, "schema_version", default=g(document, "report_metadata", "schema_version", default="-")))
        lines.append(f"| {label} | `{getattr(paths, key)}` | {status} | {schema} |")
    return "\n".join(lines) + "\n"


def audit_section(sources: dict[str, Optional[dict[str, Any]]]) -> str:
    audit = sources.get("audit")
    lines = ["## Audit (Phase 1)", ""]
    if not audit:
        return "\n".join(lines + ["_Audit artifact missing._", ""])
    plan = g(audit, "proposed_change_plan", default={})
    lines += [f"Proposed phases: {', '.join(plan) if isinstance(plan, dict) else 'n/a'}", "",
              "| id | issue |", "| --- | --- |"]
    for item in g(audit, "likely_issues_requiring_validation", default=[]) or []:
        if isinstance(item, dict):
            lines.append(f"| {fmt(item.get('id'))} | {fmt(item.get('title'))} |")
    return "\n".join(lines) + "\n"


def host_section(sources: dict[str, Optional[dict[str, Any]]]) -> str:
    host = sources.get("host")
    lines = ["## Host identification (Phase 2)", ""]
    if not host:
        return "\n".join(lines + ["_Not generated. Run `make host VIDEO=7dKqZ9ERgiQ REFERENCE=SPEAKER_24 TRIM=720`._", ""])
    prediction = g(host, "prediction", default={})
    comparison = g(host, "reference_comparison", default={})
    lines += [f"- predicted speaker: `{fmt(prediction.get('speaker_label'))}`",
              f"- inferred role: {fmt(prediction.get('inferred_role'))}",
              f"- confidence band: {fmt(prediction.get('confidence_band'))}",
              f"- reference label: `{fmt(comparison.get('reference_label'))}` | match: {fmt(comparison.get('match'))} | reference rank: {fmt(comparison.get('reference_rank'))}",
              "", "| rank | speaker | score | role |", "| --- | --- | --- | --- |"]
    for candidate in (g(host, "candidates", default=[]) or [])[:5]:
        lines.append(f"| {fmt(candidate.get('rank'))} | `{fmt(candidate.get('speaker_label'))}` | {fmt(candidate.get('heuristic_score'))} | {fmt(candidate.get('inferred_role'))} |")
    return "\n".join(lines) + "\n"


def topic_modeling_section(sources: dict[str, Optional[dict[str, Any]]]) -> str:
    report = sources.get("topic_modeling")
    lines = ["## Topic modeling (Phase 3)", ""]
    if not report:
        return "\n".join(lines + ["_Not generated. Run `make topics`._", ""])
    config = g(report, "report_metadata", "config", default={})
    aggregate = g(report, "aggregate", default={})
    episodes = g(report, "episodes", default=[])
    timeline = g(episodes[0], "subtopic_timeline", default=[]) if episodes else []
    lines += [f"- language/model: {fmt(config.get('language'))} / `{fmt(config.get('model_name'))}`",
              f"- window: {fmt(config.get('window_seconds'))} s | min topic size: {fmt(config.get('min_topic_size'))} | broad topics: {fmt(config.get('n_broad_topics'))}",
              f"- trim config: `{fmt(config.get('trim_config'))}`",
              f"- units: {fmt(g(aggregate, 'processing', 'units'))} | subtopics: {fmt(aggregate.get('subtopic_total'))} | broad: {fmt(aggregate.get('broad_total'))}",
              f"- dropped: {fmt(aggregate.get('dropped'))} | trimmed videos: {fmt(aggregate.get('trimmed_videos'))}",
              f"- episode timeline runs: {len(timeline) if isinstance(timeline, list) else 'n/a'}"]
    review = sources.get("topic_review")
    if review:
        diagnostics = g(review, "hierarchy_diagnostics", default={})
        warnings = g(review, "warnings", default=[]) or []
        lines += [f"- hierarchy: flat={fmt(diagnostics.get('flat_hierarchy'))} "
                  f"({fmt(diagnostics.get('broad_topics'))} broad vs {fmt(diagnostics.get('subtopics'))} subtopics)",
                  f"- review warnings: {', '.join(str(item.get('code')) for item in warnings) or 'none'}"]
    return "\n".join(lines) + "\n"


def topic_segmentation_section(sources: dict[str, Optional[dict[str, Any]]]) -> str:
    sample = sources.get("topic_segmentation")
    lines = ["## Topic boundary segmentation sample", ""]
    if not sample:
        return "\n".join(lines + ["_Not generated. Run `make topic-analysis`._", ""])
    processing = g(sample, "aggregate", "processing", default={})
    segments = g(sample, "aggregate", "topic_segments", default={})
    shifts = g(sample, "aggregate", "shift_events", default={})
    lines += [f"- analyzed: {fmt(processing.get('analyzed'))} | insufficient input: {fmt(processing.get('insufficient_input', 0))} "
              f"| skipped: {fmt(processing.get('skipped'))} | failed: {fmt(processing.get('failed'))}",
              f"- broad segments: {fmt(segments.get('broad_total'))} | subtopic segments: {fmt(segments.get('subtopic_total'))}",
              f"- shift events: {fmt(shifts.get('total'))}"]
    if not segments.get("subtopic_total"):
        lines += ["", "> **Stale/empty sample detected:** zero segments were produced. Regenerate with `make topic-analysis` "
                  "(the artifact predates the `final.json` fix) before using it."]
    return "\n".join(lines) + "\n"


def drift_section(sources: dict[str, Optional[dict[str, Any]]]) -> str:
    drift = sources.get("drift")
    lines = ["## Interruption -> topic drift (Phase 5)", ""]
    if not drift:
        return "\n".join(lines + ["_Not generated. Run `make drift`._", ""])
    aggregate = g(drift, "aggregate", default={})
    episodes = g(drift, "episodes", default=[])
    timeline = g(episodes[0], "timeline", default={}) if episodes else {}
    lines += [f"- interruptions: {fmt(aggregate.get('interruption_events'))} | assessed: {fmt(timeline.get('assessed_events'))} "
              f"| insufficient context: {fmt(timeline.get('insufficient_context_events'))}",
              "", "| window | layer | interruption rate | base rate | lift |",
              "| --- | --- | --- | --- | --- |"]
    for window, layers in (g(aggregate, "comparisons", default={}) or {}).items():
        for layer, values in layers.items():
            lines.append(f"| {window} s | {layer} | {fmt(values.get('interruption_rate'))} | "
                         f"{fmt(values.get('non_interruption_rate'))} | {fmt(values.get('lift'))} |")
    lines += ["", "_Lift near zero or negative means interruptions did not precede topic changes more often than chance here; "
              "window coarseness and the OSD-only interruption list bound this result._"]
    return "\n".join(lines) + "\n"


def discourse_section(sources: dict[str, Optional[dict[str, Any]]]) -> str:
    summary = sources.get("discourse")
    lines = ["## Discourse metrics + validation (Phase 4)", ""]
    if not summary:
        return "\n".join(lines + ["_Not generated. Run `make discourse` then `make discourse-review`._", ""])
    aggregate = g(summary, "aggregate", default={})
    lines += [f"- episodes analyzed: {fmt(g(aggregate, 'processing', 'successfully_analyzed'))} | skipped: {fmt(g(aggregate, 'processing', 'skipped'))}",
              f"- duration: {fmt(g(aggregate, 'duration_s', 'total'))} s | interruptions: {fmt(g(aggregate, 'interruption_attempts', 'total'))} "
              f"| overlap candidates: {fmt(g(aggregate, 'overlap_candidates', 'total'))} | transitions: {fmt(g(aggregate, 'transitions', 'total'))}"]
    review = sources.get("discourse_review")
    if review:
        cross = g(review, "aggregate", "cross_check", default={})
        episode = g(review, "episodes", default=[{}])
        structural = episode[0].get("structural_summary", {}) if episode else {}
        lines += [f"- re-derivation: {fmt(cross.get('matched'))}/{fmt(cross.get('metrics_compared'))} metrics matched "
                  f"({fmt(cross.get('mismatched'))} mismatched)",
                  f"- structural checks: out-of-order={fmt(structural.get('out_of_order'))}, "
                  f"zero-duration={fmt(structural.get('zero_duration'))}, duplicates={fmt(structural.get('duplicates'))}, "
                  f"nested overlaps={fmt(g(episode[0], 'validation', 'overlap_candidates', 'nested') if episode else None)}"]
    return "\n".join(lines) + "\n"


def reproduction_section(paths: ReportPaths) -> str:
    return "\n".join([
        "## Reproduction", "",
        "Run from the repository root with the Python 3.11 venv active. Order matters: each analysis step reads the previous artifact.", "",
        "```bash",
        "make py                 # create the .venv and install pinned deps (once)",
        "make topics             # Phase 3: topic_modeling.json + topic_windows.json + topic_modeling_review.json",
        "make topic-analysis     # embedding-based topic boundary segmentation sample",
        "make drift              # Phase 5: interruption_topic_drift.json (needs topic_modeling.json)",
        "make discourse          # Phase 4: discourse_summary.json",
        "make discourse-review   # Phase 4: discourse_summary_review.json (needs discourse_summary.json)",
        "make host VIDEO=7dKqZ9ERgiQ REFERENCE=SPEAKER_24 TRIM=720   # Phase 2: host_identification.json",
        "make report             # Phase 6: regenerate this markdown report",
        "make test               # full unit-test suite",
        "```", "",
        f"_Report source: `pilot_report.py` -> `{paths.output}`_",
    ]) + "\n"


def limitations_section(sources: dict[str, Optional[dict[str, Any]]]) -> str:
    lines = ["## Limitations", "",
             "- Diarization labels need not map to people; no speaker exclusions were applied.",
             "- Overlap candidates are detector-reconciled, not human-verified; `case=AGREE` is detector corroboration, never semantic agreement.",
             "- Interruptions are OSD-derived operational attempts; topic labels and changes are model outputs.",
             "- Topic windows are coarse; interruption associations are candidate, not causal."]
    extra: list[str] = []
    for key, label in (("topic_modeling", "Topic modeling"), ("drift", "Drift"), ("discourse_review", "Validation")):
        for item in (g(sources.get(key), "limitations", default=[]) or []):
            if isinstance(item, str) and item not in extra:
                extra.append(item)
    if extra:
        lines += ["", "Artifact-specific limitations:"] + [f"- {item}" for item in extra]
    return "\n".join(lines) + "\n"


def render(sources: dict[str, Optional[dict[str, Any]]], paths: ReportPaths = ReportPaths()) -> str:
    parts = [header(sources, paths), audit_section(sources), host_section(sources),
             topic_modeling_section(sources), topic_segmentation_section(sources),
             drift_section(sources), discourse_section(sources),
             reproduction_section(paths), limitations_section(sources)]
    return "\n".join(part.rstrip() + "\n" for part in parts)


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate the pilot episode markdown report from analysis artifacts.")
    parser.add_argument("--output", type=Path, default=ReportPaths().output)
    args = parser.parse_args()
    paths = ReportPaths(output=args.output)
    markdown = render(load_sources(paths), paths)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8") as handle:
        handle.write(markdown)
    print(f"Pilot report saved to {args.output}")


if __name__ == "__main__":
    main()
